"""Generate vocab/README.md from the vocabulary JSON files.

The JSON files are the source of truth; regenerate the README after any
vocabulary change so the documentation cannot drift. From CODE/:

    python -m knowledge_graph.vocab_docs
"""

from __future__ import annotations

import json
import sys
from pathlib import Path
from typing import Any, Dict, List

from .vocabulary import ASPECTS_PATH, INTERESTS_PATH, VOCAB_DIR, load_aspects, load_interests

README_PATH = VOCAB_DIR / "README.md"


def _seg(spec: Any) -> str:
    if isinstance(spec, str):
        return spec
    s = spec["segment"]
    if spec.get("ancestor"):
        s += f" (under {spec['ancestor']})"
    if spec.get("domains"):
        s += f" [{'/'.join(spec['domains'])}]"
    if spec.get("leaf_only"):
        s += " (leaf only)"
    return s


def _interest_text_rules(e: Dict[str, Any]) -> str:
    parts = []
    if e.get("phrases"):
        parts.append("title + features (corroborating)" if e.get("match_features", True) else "title")
    if e.get("books_title_phrases"):
        parts.append("Books title (explicit)")
    if e.get("theme"):
        parts.append("details.Theme")
    return ", ".join(parts) or "category only"


def _aspect_rules(e: Dict[str, Any]) -> str:
    out = []
    for r in e.get("rules", []):
        name = r["type"] + (f":{r['field']}" if r.get("field") else "")
        if r.get("domains"):
            name += f" [{'/'.join(r['domains'])}]"
        out.append(f"{name}: {r['confidence']}")
    if e.get("component_guard"):
        out.append("component guard")
    return ", ".join(out)


def render() -> str:
    ij = json.loads(Path(INTERESTS_PATH).read_text(encoding="utf-8"))
    aj = json.loads(Path(ASPECTS_PATH).read_text(encoding="utf-8"))
    iv, av = load_interests(), load_aspects()  # also validates both files
    conf, ri, agg = ij["confidence"], aj["review_inference"], aj["review_inference"]["aggregation"]
    L: List[str] = []
    w = L.append
    w("# Gift Concierge KG vocabularies\n")
    w(f"- `interests.json`: **{len(iv.concepts)} interest labels**, version `{iv.version}`")
    w(f"- `aspects.json`: **{len(av.concepts)} attribute aspects** (from listing metadata) and "
      f"**{len(av.reserved)} quality aspects** (from reviews only), version `{av.version}`\n")
    w("This file is generated by `python -m knowledge_graph.vocab_docs` from the JSON vocabularies, "
      "which are the source of truth. Do not edit it by hand.\n")

    w("## Rules that apply to everything\n")
    w("- **Confidence values are heuristic rule scores, not calibrated probabilities.** They rank evidence "
      "tiers and nothing more. No precision has been measured yet; see `../eval/README.md`.")
    w("- **Aggregation: max.** An edge with several evidence items gets the highest item score. Scores are "
      "never combined (no noisy-OR). Every distinct item is kept in `evidence_list`, de-duplicated.")
    w("- **MATCHES is optional.** A product with no interest edge must remain eligible for recommendation. "
      "Use MATCHES to boost or explain, never to filter.")
    w("- **No recipient or occasion inference.** Recipients, occasions, age and budget belong in the "
      "conversation state.")
    w("- **No subjective quality from seller text.** Quality aspects have no listing rules; validation "
      "rejects any quality HAS_ASPECT edge that is not a review aggregate.")
    w("- **Not mapped on purpose:** `Religion & Spirituality > Occult & Paranormal`.\n")

    w("## Interests\n")
    w("### Evidence tiers\n")
    w("| Evidence | Score | Notes |")
    w("|---|---|---|")
    w(f"| Category-path rule | {conf['category']} | `match_type = primary` |")
    w(f"| `details.Theme` value | {conf['details_theme']} | ignored when Theme lists more than "
      f"{ij.get('theme_max_values')} values |")
    w(f"| Title phrase (Handmade, Toys) | {conf['title']} | `match_type = themed` unless a category rule also fired |")
    w(f"| Title phrase, Books (explicit list only) | {conf['title_books']} | `match_type = primary` (the book is about it) |")
    w(f"| Feature phrase (Handmade, Toys only) | {conf['features']} | **corroborating only**: never creates "
      "an edge on its own |\n")
    w("### Text matching\n")
    w("Whole words, case-insensitive; a space also matches a hyphen. A text match is dropped when it:\n")
    w("- overlaps an `exclude` phrase (\"dog\" in \"hot dog\");")
    w("- is negated in its clause (\"not printed on wood\");")
    w("- sits in an SEO keyword list of recipients/occasions, a long list of compatible uses, a run of five "
      "or more one- or two-word items (\"Jewelry, Fishing Lures, Dolls, Hobby, RC\"), or a compatibility clause "
      "(\"Fit for TCG Yugioh card\");")
    w("- is in a cross-sell sentence (\"You Can Consider This Cat Puzzle\");")
    w("- belongs to a product whose category path contains one of the concept's "
      "`suppress_text_in_categories`;")
    w("- belongs to a product whose title head names a suppressed product class:\n")
    for name, spec in ij.get("text_suppression", {}).items():
        extra = " A phrase introduced by \"for\"/\"as\" is a suggested use and does not count." \
            if spec.get("use_suggestion_exempt") else ""
        w(f"  - `{name}`: {spec.get('description', '')}{extra} Phrases: "
          + ", ".join(f"\"{p}\"" for p in spec["phrases"]) + ".")
    w("\n  The *title head* is the text before the first `,` `;` `|` `~` ` - ` or bracket, so SEO tails "
      "(\"Beach Ball, Superhero Toys ... Pool Party Favors\") do not change the product class. "
      "Category rules still apply to suppressed products. Books are never suppressed.\n")
    w("An interest supported only by feature phrases is counted as an *incidental mention* "
      "(`interest_incidental_mentions` flag) and creates no edge.\n")
    w("### Labels\n")
    w("| Label | Display name | Description | Category rules | Text rules |")
    w("|---|---|---|---|---|")
    for e in ij["interests"]:
        cats = "; ".join(_seg(s) for s in e.get("category", [])) or "—"
        w(f"| `{e['label']}` | {e.get('display_name', '')} | {e.get('description', '')} | {cats} | "
          f"{_interest_text_rules(e)} |")
    w("")

    w("## Attribute aspects (objective, from listings)\n")
    w("Each HAS_ASPECT edge records `evidence_type`: `structured` (details/categories/domain) or "
      "`listing_stated` (seller-written title/features). Listing-stated attributes are seller statements, "
      "not verified facts. Cross-sell sentences in features are ignored. Materials use a *component guard*: "
      "counted kit contents (\"1 Plastic Funnel, 1 Wooden Stick, 1 Plastic Flask\") and spare, replaced or "
      "\"not included\" parts are not the product's material.\n")
    w("| Label | Display name | Description | Rules (type: score) |")
    w("|---|---|---|---|")
    for e in aj["attribute_aspects"]:
        w(f"| `{e['label']}` | {e.get('display_name', '')} | {e.get('description', '')} | {_aspect_rules(e)} |")
    w("")

    w("## Quality aspects (review evidence only)\n")
    w("Matched only in review text by `review_inference.py`, never in listing text.\n")
    w("**Per review** (`Review -SUPPORTS-> Aspect`): each matched clause is an evidence item with "
      "`evidence_polarity` positive, negative or neutral, its cue span, and confidence "
      f"(direct {ri['confidence']['direct']}, negated positive {ri['confidence']['negated_positive']}, "
      f"neutral {ri['confidence']['neutral']}). The edge's `polarity` is positive or negative when all "
      "non-neutral items agree, `mixed` when they disagree, else neutral. The edge also stores rating, "
      "verified_purchase and helpful_vote.\n")
    w("- A negated positive cue (\"not sturdy\") is negative. A negated negative cue (\"hasn't broken\") is "
      "**neutral, not positive**.")
    w("- Hedged, counterfactual or questioning text (\"hope it lasts\", \"looked like it would be "
      "informative\", \"is it durable?\") is neutral.")
    w("- Negation and hedges are scoped to the clause up to the nearest comma before the cue. Sentences are "
      "split into clauses at contrast words (" + ", ".join(ri["contrast_markers"]) + ").")
    w("- `context_exclude`: an aspect is skipped in a clause mentioning one of its context words "
      "(durability is not judged from clauses about the box, packaging or shipping).")
    w("- **A star rating is never evidence on its own.** A positive item in a review rated "
      f"<= {agg['conflict_max_rating']} is flagged `rating_conflict` and does not count toward HAS_ASPECT.\n")
    w("**Per product** (`Product -HAS_ASPECT-> quality aspect`, source `review_aggregate`): created only when "
      f"at least **{agg['min_positive_reviews']} distinct positive reviews** (identical texts count once; "
      "rating-conflict and mixed reviews excluded) support the aspect and positive reviews are at least "
      f"**{agg['positive_to_critical_ratio']}x** the negative plus mixed reviews. The edge cites one positive "
      "clause per supporting review and stores all counts. **Negative evidence never becomes HAS_ASPECT**: "
      f"an aspect with at least {agg['concern_min_negative_reviews']} negative reviews and more negatives than "
      "positives is recorded as a *concern* in the product's `review_aspect_signals`.\n")
    w("| Label | Display name | Description | Domains | Positive cues | Negative cues |")
    w("|---|---|---|---|---|---|")
    for e in aj["quality_aspects"]:
        rc = e["review_cues"]
        doms = "/".join(d.replace(" Products", "").replace(" & Games", "") for d in rc["domains"]) or "all"
        w(f"| `{e['label']}` | {e.get('display_name', '')} | {e.get('description', '')} | {doms} | "
          f"{len(rc['positive'])} | {len(rc['negative'])} |")
    w("")

    w("## Aligning with LLM constraint extraction\n")
    w("- The `label` values in `interests.json` are the shared interest IDs. The conversation component "
      "should restrict its `interests` output to these labels (e.g. a JSON-schema enum). The `aliases` give "
      "example user phrasings for its prompt.")
    w("- Specific franchises or terms (e.g. \"Star Wars\", \"sourdough\") go in a free-text field for "
      "BM25/semantic retrieval. They are not new KG labels.")
    w("- \"Loves reading\" is a domain preference (Books), not an interest.")
    w(f"- Both sides record the vocabulary version (`{iv.version_tag}`). The label set has not changed "
      "since 1.0.0.\n")

    w("## Versioning\n")
    w("- **Patch**: phrase or exclusion fixes that do not change labels or edge semantics.")
    w("- **Minor**: added labels, or new matching policies or edge attributes that existing consumers can "
      "ignore (e.g. `match_type`, feature evidence becoming corroborating-only, review cues).")
    w("- **Major**: renamed or removed labels.\n")
    for name, data in (("interests", ij), ("aspects", aj)):
        w(f"### `{name}.json` changelog\n")
        for c in data.get("changelog", []):
            w(f"- **{c['version']}**: " + "; ".join(c["changes"]))
        w("")
    return "\n".join(L).rstrip() + "\n"


def main(argv=None) -> int:
    README_PATH.write_text(render(), encoding="utf-8", newline="\n")
    print(f"Wrote {README_PATH}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
